import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { appPath } from '../app/lib/app-path.ts';
let checks = 0;
const equal = (a, b, label) => { assert.deepEqual(a, b, label); checks++; };
const brand = readFileSync('app/components/BrandHomeButton.tsx', 'utf8');
const page = readFileSync('app/page.tsx', 'utf8');
const css = readFileSync('app/globals.css', 'utf8');
const png = readFileSync('public/tabito-logo-253970.png');
equal(png.subarray(0, 8).toString('hex'), '89504e470d0a1a0a', 'valid supplied PNG');
equal([png.readUInt32BE(16), png.readUInt32BE(20)], [2007, 783], 'original aspect ratio');
equal(brand.includes("appPath('/tabito-logo-253970.png')"), true, 'asset respects deployment prefix');
equal(appPath('/tabito-logo-253970.png', '/payroll'), '/payroll/tabito-logo-253970.png', 'subdirectory logo URL');
equal(brand.includes('返回首页') && brand.includes('aria-label='), true, 'accessible home label');
equal(brand.includes('type="button"') && brand.includes('onClick={onHome}'), true, 'native keyboard-operable button');
equal(page.includes("<BrandHomeButton onHome={() => onNavigate('/')} />"), true, 'reuse guarded home navigation');
equal(css.includes('.brand-lockup img { display: block; width: 100%; height: auto;'), true, 'responsive logo never stretches');
equal(css.includes('background: #253970;'), true, 'sidebar matches supplied background');
equal(css.includes('grid-template-columns: 208px minmax(0, 1fr);') && css.includes('width: 208px;'), true, 'sidebar and content grid share compact width');
equal(css.includes('width: min(100%, 200px);'), true, 'mobile logo stays compact');
console.log(JSON.stringify({ result: 'PASS', checks }));
