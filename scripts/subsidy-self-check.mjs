async function req(path, actor, method = 'GET', body, expected = 200) {
  const response = await fetch(base + path, {method, headers: {origin: base, ...(actor?.cookie ? {cookie: actor.cookie} : {}), ...(body ? {'content-type': 'application/json'} : {})}, body: body ? JSON.stringify(body) : undefined});
  const data = await response.json();
  equal(response.status, expected, `${method} ${path}: ${JSON.stringify(data)}`);
  return {...data, cookie: response.headers.get('set-cookie')?.split(';')[0]};
}
